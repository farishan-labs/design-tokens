import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { resolve, basename } from "node:path";
import {
  applyInheritance,
  parseResolver,
  resolveAliases,
  resolveResolver,
  validate,
} from "@styleframe/dtcg";

const ROOT = resolve(import.meta.dir, "..");
const SRC_TOKENS = resolve(ROOT, "src/tokens");
const CLIENT = resolve(ROOT, "scripts", "preview-client.js");

const args = process.argv.slice(2);

async function loadResolved(): Promise<{ raw: unknown; count: number }> {
  const resolverRaw = JSON.parse(readFileSync(resolve(SRC_TOKENS, "tokens.resolver.json"), "utf8"));
  const resolver = parseResolver(resolverRaw);
  const loader = async (ref: string) => JSON.parse(readFileSync(resolve(SRC_TOKENS, ref), "utf8"));
  const resolved = await resolveResolver(resolver, { theme: "light" }, loader);
  const inherited = applyInheritance(resolved as any);
  const aliased = resolveAliases(inherited as any, { strict: false });
  const vErrors = validate(aliased as any);
  if (vErrors.length) {
    console.error("Resolved validation errors:", vErrors.length);
    process.exit(1);
  }
  return { raw: aliased, count: countTokens(aliased) };
}

function countTokens(n: unknown): number {
  if (typeof n !== "object" || n === null) return 0;
  const o = n as Record<string, unknown>;
  if ("$value" in o) return 1;
  let c = 0;
  for (const [k, v] of Object.entries(o)) {
    if (k.startsWith("$")) continue;
    c += countTokens(v);
  }
  return c;
}

let raw: unknown;
let inputLabel: string;
if (args[0]) {
  const inputPath = resolve(args[0]);
  if (!existsSync(inputPath)) {
    console.error(`Tokens file not found: ${inputPath}`);
    process.exit(1);
  }
  raw = JSON.parse(readFileSync(inputPath, "utf8"));
  inputLabel = basename(inputPath);
} else {
  const r = await loadResolved();
  raw = r.raw;
  inputLabel = "tokens (light mode)";
}

const count = countTokens(raw);
const safeJson = JSON.stringify(raw).replace(/</g, "\\\\u003c");
