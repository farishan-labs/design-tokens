const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Design tokens preview — ${basename(inputPath)}</title>
<style>${style}</style>
</head>
<body>
<h1>Design tokens preview</h1>
<p class="meta">${basename(inputPath)} · ${count} tokens</p>
<div id="root"></div>
<footer>Generated by @farishan-labs/design-tokens · view-only</footer>
<script>const tokens = ${safeJson};</script>
<script>${clientJs}</script>
</body>
</html>`;

const outPath = resolve(ROOT, "dist", "preview.html");
writeFileSync(outPath, html);
console.log(`Preview written: ${outPath}`);

